using OtpNet;
using Microsoft.AspNetCore.DataProtection;

namespace SecureVotingApp.Services;
//Time-based One-Time Password
public class TotpService
{   
    private readonly IDataProtector _protector;

    public TotpService(IDataProtectionProvider provider)
    {
        _protector = provider.CreateProtector("SecureVotingApp.TotpSecrets.2FA");
    }

    //Generates a random 20-byte TOTP secret and converts it to Base32
    public string GenerateSecret()
    {
        byte[] secret = KeyGeneration.GenerateRandomKey(20);
        return Base32Encoding.ToString(secret);
    }
    /*   Since 1 byte = 8 bits:
     *   20 bytes × 8 = 160 bits.
     *   Why 160 bits?
     *   TOTP commonly uses HMAC-SHA1, which uses a 160-bit key as a standard recommendation.
     *   Your authenticator app and backend share this secret to calculate matching six-digit codes every 30 seconds.
     */

    // Encrypts the secret using ASP.NET Core Data Protection
    public string EncryptSecret(string secret)
    {
        return _protector.Protect(secret);
    }

    // Decrypt the stored TOTP secret when verifying a login code.
    public string DecryptSecret(string encryptedSecret)
    {
        return _protector.Unprotect(encryptedSecret);
    }

    //Creates the URI used by the frontend to render the QR code
    public string GenerateTOTPSetupUri(string email, string secret)
    {   
        string encodedEmail = Uri.EscapeDataString(email);

        return "otpauth://totp/SecureVotingApp:" + encodedEmail + "?secret=" + secret + "&issuer=SecureVotingApp&algorithm=SHA1&digits=6&period=30";
    }   
    /* 
       Example: otpauth://totp/SecureVotingApp:user@example.com?secret=BASE32SECRET&issuer=SecureVotingApp&algorithm=SHA1&digits=6&period=30

        This tells Google Authenticator or Microsoft Authenticator:
        - SecureVotingApp — the application name.
        - user@example.com — which account the code belongs to.
        - secret — the shared Base32 secret generated by your backend.
        - digits=6 — generate six-digit codes.
        - period=30 — generate a new code every 30 seconds.
        - algorithm=SHA1 — the TOTP algorithm we're using.
    */


    //Verifies the submitted code and returns the matching time step
    public bool VerifyTOTPCode(string secret, string code, out long timeStepMatched)
    {
        byte[] secretBytes = Base32Encoding.ToBytes(secret);
        
        var totp = new Totp(secretBytes);

        return totp.VerifyTotp( 
            code,
            out timeStepMatched,
            new VerificationWindow(previous: 1, future: 1)
        );
    }
    /*  
        Base32Encoding.ToBytes(secret) converts the stored Base32 secret back into its original bytes.
        new Totp(secretBytes) creates a validator using that secret.
        VerifyTotp() checks whether the six-digit code matches.
        VerificationWindow(previous: 1, future: 1) allows one 30-second interval on either side of the current interval to account for small clock differences.
    */
}